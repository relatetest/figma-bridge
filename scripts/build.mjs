#!/usr/bin/env node
// Regenerates every file derived from skill frontmatter, so there is one source of truth:
//   .claude-plugin/plugin.json       version from package.json
//   .github/CODEOWNERS               metadata.owner of each skill
//   README.md                        the catalog between the catalog markers
// Which of them a repo generates is set in relate.config.json → generate.
// The marketplace is not here: it lives in the hub repo, which pins this plugin to a release tag.
//
//   node scripts/build.mjs           write the files
//   node scripts/build.mjs --check   fail if any of them is out of date (CI)

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { CONFIG, ROOT, loadSkills, firstSentence, invocation, readText } from './lib.mjs';

const check = process.argv.includes('--check');
const pkg = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const skills = loadSkills().filter((s) => s.exists && s.data && s.data.name);

const json = (o) => JSON.stringify(o, null, 2) + '\n';

function pluginJson() {
  const p = CONFIG.plugin;
  return json({
    name: p.name,
    version: pkg.version,
    description: p.description,
    author: p.author,
    homepage: p.homepage,
    repository: `https://github.com/${CONFIG.repo}`,
    license: p.license,
    keywords: p.keywords,
  });
}

function codeowners() {
  const lines = [
    '# Generated by scripts/build.mjs from metadata.owner. Do not edit by hand.',
    `* ${CONFIG.maintainers}`,
    '',
  ];
  for (const s of skills) {
    const owner = s.data.metadata && s.data.metadata.owner;
    if (!owner) continue;
    const who = [...new Set([owner, CONFIG.maintainers])].join(' ');
    lines.push(`/${CONFIG.skillsDir}/${s.dirName}/ ${who}`);
    lines.push(`/${CONFIG.evalsDir}/${s.dirName}/ ${who}`);
  }
  return lines.join('\n') + '\n';
}

const STATUS = { experimental: 'пробный', stable: 'стабильный', deprecated: 'устарел' };
const INVOKE = { 'auto + manual': 'сам и по имени', manual: 'только по имени', 'agent only': 'только сам' };

function cell(text) {
  return String(text).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function catalog() {
  if (skills.length === 0) return 'Скиллов пока нет. Первый создаётся командой `npm run new -- <имя> --type knowledge --owner @login --category <категория>`.\n';
  const out = [];
  for (const [key, title] of Object.entries(CONFIG.categories)) {
    const group = skills.filter((s) => s.data.metadata && s.data.metadata.category === key);
    if (group.length === 0) continue;
    out.push(`### ${title}`, '', '| Скилл | Что делает | Запуск | Статус | Владелец |', '|---|---|---|---|---|');
    for (const s of group) {
      const m = s.data.metadata;
      let status = STATUS[m.status] || m.status;
      if (m.status === 'deprecated' && m['replaced-by']) status += ` → \`${m['replaced-by']}\``;
      out.push(
        `| [\`${s.dirName}\`](${CONFIG.skillsDir}/${s.dirName}/SKILL.md) | ${cell(firstSentence(s.data.description))} | ${INVOKE[invocation(s.data)]} | ${status} | ${m.owner} |`,
      );
    }
    out.push('');
  }
  return out.join('\n');
}

function withCatalog(readme) {
  const start = '<!-- catalog:start -->';
  const end = '<!-- catalog:end -->';
  const a = readme.indexOf(start);
  const b = readme.indexOf(end);
  if (a === -1 || b === -1 || b < a) throw new Error(`README.md must contain ${start} and ${end}`);
  return readme.slice(0, a + start.length) + '\n' + catalog() + readme.slice(b);
}

const readmePath = path.join(ROOT, 'README.md');
const gen = CONFIG.generate || { pluginJson: true, codeowners: true, catalog: true };
const targets = [];
if (gen.pluginJson) targets.push(['.claude-plugin/plugin.json', pluginJson()]);
if (gen.codeowners) targets.push(['.github/CODEOWNERS', codeowners()]);
if (gen.catalog) targets.push(['README.md', withCatalog(readText(readmePath))]);

let stale = 0;
for (const [relPath, content] of targets) {
  const full = path.join(ROOT, relPath);
  const current = existsSync(full) ? readText(full) : null;
  if (current === content) continue;
  if (check) {
    stale++;
    console.log(`✗ ${relPath} is out of date`);
  } else {
    mkdirSync(path.dirname(full), { recursive: true });
    writeFileSync(full, content);
    console.log(`  wrote ${relPath}`);
  }
}
if (check) {
  if (stale) {
    console.log('\nRun "npm run build" and commit the result.');
    process.exit(1);
  }
  console.log('✓ generated files are up to date');
}
